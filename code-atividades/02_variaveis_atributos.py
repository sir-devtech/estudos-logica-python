# Variáveis e atribuição
# Força, velocidade e sorte do combatente.

forca = int(input("Força: "))
velocidade = int(input("Velocidade: "))
sorte = int(input("Sorte: "))

print(f"Atributos -> força={forca}, velocidade={velocidade}, sorte={sorte}")
total = forca + velocidade + sorte
print(f"Soma dos atributos: {total}")
